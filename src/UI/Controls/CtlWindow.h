#pragma once

#include <string>

#include "UI/Services/Localization/LoclText.h"

///----------------------------------------------------------------------------------------------------
/// IWindow Interface Class
///----------------------------------------------------------------------------------------------------
class IWindow
{
	public:
	///----------------------------------------------------------------------------------------------------
	/// Render:
	/// 	Renders the given window.
	///----------------------------------------------------------------------------------------------------
	virtual void Render() = 0;

	///----------------------------------------------------------------------------------------------------
	/// GetName:
	/// 	Returns the name of the window.
	///----------------------------------------------------------------------------------------------------
	const std::string& GetName();

	///----------------------------------------------------------------------------------------------------
	/// GetDisplayName:
	/// 	Returns the translated display name of the window.
	///----------------------------------------------------------------------------------------------------
	const char* GetDisplayName();

	///----------------------------------------------------------------------------------------------------
	/// Invalidate:
	/// 	Invalidates all dynamic resources and refreshes them.
	///----------------------------------------------------------------------------------------------------
	virtual void Invalidate();

	///----------------------------------------------------------------------------------------------------
	/// GetVisibleStatePtr:
	/// 	Returns a pointer to the visible state bool.
	///----------------------------------------------------------------------------------------------------
	virtual bool* GetVisibleStatePtr();

	protected:
	std::string Name;
	CText       DisplayName;
	bool        IsVisible = false;
	bool        IsInvalid = false;
};
