## Generates src/UI/Services/Localization/LoclTextIds.h from res/Locales/en/DisplayStrings.json:
## one constant per text, holding its key ("Common.Accept"), with the English text as its comment.
## Runs as a pre-build step. Writes the header only when its content changed, so it does not trigger rebuilds.
## Usage: powershell -NoProfile -ExecutionPolicy Bypass -File tools\generate-locale-ids.ps1

$ErrorActionPreference = "Stop"

$root   = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root "res\Locales\en\DisplayStrings.json"
$target = Join-Path $root "src\UI\Services\Localization\LoclTextIds.h"

$keywords = @(
	"alignas", "alignof", "and", "asm", "auto", "bool", "break", "case", "catch", "char", "class", "const", "constexpr",
	"continue", "default", "delete", "do", "double", "else", "enum", "explicit", "export", "extern", "false", "float",
	"for", "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "nullptr",
	"operator", "or", "private", "protected", "public", "register", "return", "short", "signed", "sizeof", "static",
	"struct", "switch", "template", "this", "throw", "true", "try", "typedef", "typename", "union", "unsigned", "using",
	"virtual", "void", "volatile", "while", "xor"
)

function Fail([string]$aMessage)
{
	Write-Host "generate-locale-ids: error: $aMessage"
	exit 1
}

if (-not (Test-Path $source)) { Fail "$source not found. Is the res/Locales submodule checked out?" }

$json = [System.IO.File]::ReadAllText($source, [System.Text.Encoding]::UTF8) | ConvertFrom-Json

## Texts in file order: path segments and English text.
$texts = New-Object System.Collections.Generic.List[object]

function Walk($aNode, [string[]]$aPath)
{
	foreach ($prop in $aNode.PSObject.Properties)
	{
		$path = $aPath + $prop.Name

		if ($prop.Name -notmatch '^[A-Za-z_][A-Za-z0-9_]*$' -or $keywords -contains $prop.Name)
		{
			Fail "Key '$($path -join '.')': '$($prop.Name)' is not a valid C++ identifier."
		}

		if ($prop.Value -is [string])
		{
			if ($path.Count -lt 2) { Fail "Key '$($prop.Name)' must be inside an area, e.g. 'Common.$($prop.Name)'." }
			$texts.Add([pscustomobject]@{ Path = $path; Text = $prop.Value })
		}
		elseif ($prop.Value -is [System.Management.Automation.PSCustomObject])
		{
			Walk $prop.Value $path
		}
		else
		{
			Fail "Key '$($path -join '.')' must be a string or an object."
		}
	}
}

Walk $json.Texts @()

if ($texts.Count -eq 0) { Fail "No texts found in $source." }

$nl = "`r`n"
$sb = New-Object System.Text.StringBuilder

[void]$sb.Append("///----------------------------------------------------------------------------------------------------$nl")
[void]$sb.Append("/// Generated by tools/generate-locale-ids.ps1 from res/Locales/en/DisplayStrings.json. Do not edit.$nl")
[void]$sb.Append("/// Each constant is a display string: .Text() translates it, .Key() is its key. Included by LoclText.h.$nl")
[void]$sb.Append("///----------------------------------------------------------------------------------------------------$nl$nl")
[void]$sb.Append("#pragma once$nl")

## Constants grouped by namespace, in order of first appearance.
$groups = New-Object System.Collections.Specialized.OrderedDictionary
foreach ($text in $texts)
{
	$ns = ($text.Path[0..($text.Path.Count - 2)]) -join "::"
	if (-not $groups.Contains($ns)) { $groups[$ns] = New-Object System.Collections.Generic.List[object] }
	$groups[$ns].Add($text)
}

foreach ($ns in $groups.Keys)
{
	[void]$sb.Append("$($nl)namespace Lang::$ns$nl{$nl")
	foreach ($text in $groups[$ns])
	{
		## A trailing backslash would continue the comment onto the constant.
		$comment = ($text.Text -replace '[\r\n]+', ' ').Trim().TrimEnd('\')
		[void]$sb.Append("`t/// $comment$nl")
		[void]$sb.Append("`tinline constexpr CText $($text.Path[-1]){ `"$($text.Path -join '.')`" };$nl")
	}
	[void]$sb.Append("}$nl")
}

$content = $sb.ToString()

if ((Test-Path $target) -and ([System.IO.File]::ReadAllText($target) -eq $content))
{
	exit 0
}

[System.IO.File]::WriteAllText($target, $content, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "generate-locale-ids: wrote $($texts.Count) display strings."
